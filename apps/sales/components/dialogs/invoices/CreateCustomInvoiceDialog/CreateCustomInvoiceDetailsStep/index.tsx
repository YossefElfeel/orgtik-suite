"use client";

import { useEffect, useMemo } from "react";
import type { UseFormReturn } from "react-hook-form";
import { useWatch } from "react-hook-form";
import TextFormEle from "@/components/ui/form/text-form-element";
import TextEditorFormEle from "@/components/ui/form/text-editor-form-element";
import ComboboxFormEle from "@/components/ui/form/combobox-form-element";
import { CustomerSelectField } from "@/components/shared/EntitySelectFields";
import { mapCurrencyOptionsToComboboxOptions } from "@/lib/currency";
import { useGetCurrencyOptionsQuery } from "@/redux/features/currency/currencyApi";
import type { CustomInvoiceFormValues } from "@/schemas/custom-invoice";
import { useTranslations } from "next-intl";

type Props = {
  form: UseFormReturn<CustomInvoiceFormValues>;
};

export default function CreateCustomInvoiceDetailsStep({ form }: Props) {
  const t = useTranslations("invoices");
  const customerId = useWatch({ control: form.control, name: "customerId" });

  const { data: currenciesResponse, isLoading: isLoadingCurrencies } =
    useGetCurrencyOptionsQuery();
  const currencyOptions = useMemo(
    () => mapCurrencyOptionsToComboboxOptions(currenciesResponse?.data ?? []),
    [currenciesResponse?.data],
  );

  useEffect(() => {
    const currentCurrency = form.getValues("currency");
    const firstOption = currenciesResponse?.data?.[0]?.code;
    if (!currentCurrency && firstOption) {
      form.setValue("currency", firstOption);
    }
  }, [form, currenciesResponse?.data]);

  useEffect(() => {
    if (!customerId?.trim()) return;

    form.setValue("invoiceNumber", "");
    form.setValue("billingName", "");
    form.setValue("billingContactPerson", "");
    form.setValue("billingEmail", "");
    form.setValue("billingPhone", "");
    form.setValue("billingAddress", "");
  }, [customerId, form]);

  const hasCustomer = Boolean(customerId?.trim());

  return (
    <div className="flex flex-col gap-5">
      <CustomerSelectField
        form={form}
        name="customerId"
        enabled
        label={t("customer")}
        placeholder={t("searchCustomer")}
        searchPlaceholder={t("searchCustomers")}
        optional
        clearable
      />

      {!hasCustomer ? (
        <>
          <TextFormEle
            form={form}
            name="invoiceNumber"
            label={t("invoiceNumber")}
            placeholder={t("autoGeneratedIfEmpty")}
            optional
          />

          <div className="grid grid-cols-1 gap-4 sm:grid-cols-2">
            <TextFormEle
              form={form}
              name="billingName"
              label={t("companyName")}
              placeholder={t("billingCompanyName")}
            />
            <TextFormEle
              form={form}
              name="billingContactPerson"
              label={t("customerName")}
              placeholder={t("contactPersonPlaceholder")}
              optional
            />
          </div>

          <div className="grid grid-cols-1 gap-4 sm:grid-cols-2">
            <TextFormEle
              form={form}
              name="billingEmail"
              label={t("billingEmail")}
              type="email"
              placeholder={t("billingEmailPlaceholder")}
              optional
            />
            <TextFormEle
              form={form}
              name="billingPhone"
              label={t("billingPhone")}
              placeholder="+1 555 000 0000"
              optional
            />
          </div>

          <TextEditorFormEle
            form={form}
            name="billingAddress"
            label={t("billingAddress")}
            placeholder={t("billingAddressPlaceholder")}
            optional
          />
        </>
      ) : null}

      <div className="grid grid-cols-1 gap-4 sm:grid-cols-2">
        <ComboboxFormEle
          form={form}
          name="currency"
          label={t("currency")}
          placeholder={t("selectCurrency")}
          options={currencyOptions}
          disabled={isLoadingCurrencies}
        />
        <TextFormEle
          form={form}
          name="dueDate"
          label={t("dueDate")}
          type="date"
          optional
        />
      </div>

      <TextEditorFormEle
        form={form}
        name="description"
        label={t("invoiceDescription")}
        placeholder={t("describeInvoice")}
        optional
      />
    </div>
  );
}
