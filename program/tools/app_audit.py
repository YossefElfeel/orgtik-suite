"""An app's audit inventory, assembled from what the audit tools recorded.

    python tools/app_audit.py files

Reads, for the app:
    audits/inventory/routes.csv, components.csv     what the code has
    audits/baseline-metrics.csv                      the static counts
    audits/<app>/sweep-baseline.json                 how each route behaved
    audits/<app>/deadends-baseline.json              what pressing each control did
    audits/<app>/flows/walks.json                    the flow walks (if walked)
    audits/<app>/issues.csv                          the issue log (written by the auditor)

Writes audits/<app>/inventory.md: the audit method's summary file (audits/README.md). Re-run it
whenever one of those inputs changes.
"""
import csv
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

PROGRAM = Path(__file__).resolve().parent.parent
AUDITS = PROGRAM / "audits"

# Local primitive → the @orgtik/ui component that replaces it (p1-scope.md).
LIBRARY = {
    "button": "Button, IconButton", "form": "Field + createRHFField", "label": "Field", "input": "Input, PasswordInput",
    "textarea": "Textarea", "checkbox": "Checkbox", "switch": "Switch", "radio-group": "RadioGroup, SegmentedControl",
    "select": "Select", "dialog": "Dialog, ConfirmDialog", "reusable-dialog": "ConfirmDialog", "sheet": "Sheet",
    "dropdown-menu": "Menu", "context-menu": "Menu (context)", "popover": "Popover", "tooltip": "Tooltip",
    "badge": "Badge, StatusBadge", "avatar": "Avatar", "card": "Card", "skeleton": "Skeleton", "sonner": "Toast",
    "tabs": "Tabs", "pagination": "Pagination", "calendar": "Calendar, DatePicker", "chart": "charts (Tier 2)",
    "accordion": "Accordion", "collapsible": "Collapsible", "scroll-area": "ScrollArea", "separator": "Separator",
    "progress": "Progress, Meter", "command": "Combobox, CommandPalette", "table": "DataTable",
}


def read_csv(path):
    if not path.exists():
        return []
    with open(path, encoding="utf-8-sig", newline="") as fh:
        return list(csv.DictReader(fh))


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def main(app):
    here = AUDITS / app
    routes = [r for r in read_csv(AUDITS / "inventory" / "routes.csv") if r["app"] == app]
    comps = [c for c in read_csv(AUDITS / "inventory" / "components.csv") if c["app"] == app]
    metrics = next((m for m in read_csv(AUDITS / "baseline-metrics.csv") if m["app"] == app), {})
    sweep = read_json(here / "sweep-baseline.json") or {"results": []}
    dead = read_json(here / "deadends-baseline.json") or {"pages": [], "tally": {}}
    walks = (read_json(here / "flows" / "walks.json") or {}).get("walks", [])
    issues = read_csv(here / "issues.csv")

    by_route = {r["route"]: r for r in sweep["results"]}
    outcomes = defaultdict(Counter)
    for p in dead["pages"]:
        for x in p.get("results", []):
            outcomes[p["route"]][x["outcome"]] += 1

    md = [f"# {app}: audit inventory", ""]
    md.append(f"Assembled by `tools/app_audit.py {app}` from the route inventory, the baseline sweep ({sweep.get('at', '?')[:10]}, as {sweep.get('as', '?')}, {sweep.get('combo', '?')}), the dead-end run, the flow walks and the issue log. Screenshots are regenerated by the kit; git ignores them.")
    md += ["", "## Routes", "", "| Route | File | Loaded | Console | Uncaught | Failing API | axe crit/serious | Controls pressed | Needs a look |", "|---|---|---|---|---|---|---|---|---|"]
    for r in routes:
        s = by_route.get(r["route"], {})
        o = outcomes.get(r["route"], Counter())
        pressed = sum(v for k, v in o.items() if k not in ("skipped", "broken link"))
        look = ", ".join(f"{k} {v}" for k, v in o.items() if k not in ("navigated", "opened", "changed", "skipped"))
        loaded = "—" if not s else ("yes" if str(s.get("status", "")).startswith(("2", "3")) and not s.get("auth_redirect") else f"no ({s.get('status') or s.get('error', '')})")
        md.append(f"| `{r['route']}` | `{r['file'].split('/', 1)[-1]}` | {loaded} | {s.get('console_errors', '')} | {s.get('page_errors', '')} | {s.get('api_errors', '')} | {s.get('axe_critical', '')}/{s.get('axe_serious', '')} | {pressed or ''} | {look} |")

    if walks:
        md += ["", "## Flows walked", "", "| Flow | Steps passed | Result |", "|---|---|---|"]
        for w in walks:
            ok = sum(1 for s in w["steps"] if s["ok"])
            failed = [s for s in w["steps"] if not s["ok"]]
            result = "passes" if not failed else "; ".join(f"step {s['n']} {s['name']}: {s['note']}" for s in failed)
            md.append(f"| {w['id']}: {w['title']} | {ok}/{len(w['steps'])} | {result} |")

    md += ["", "## Components → library", "", "| Local | Kind | Imported by (files) | Library equivalent |", "|---|---|---|---|"]
    for c in sorted(comps, key=lambda c: -int(c["imported_by"] or 0))[:40]:
        eq = LIBRARY.get(c["name"], "decide in the wave" if c["kind"] != "ui" else "—")
        md.append(f"| `{c['name']}` | {c['kind']} | {c['imported_by']} | {eq} |")
    if len(comps) > 40:
        md.append(f"| … {len(comps) - 40} more in `audits/inventory/components.csv` | | | |")

    t = dead.get("tally", {})
    md += ["", "## Baseline metrics", "", "Each count is where the wave starts; it may only go down.", "", "| Metric | Value |", "|---|---|"]
    for k in ["files", "lines", "raw_hex", "default_palette_classes", "physical_direction_classes", "inline_style_objects", "lucide_imports", "iconify_uses", "t_calls", "literal_jsx_text", "token_in_url", "hardcoded_passwords"]:
        if k in metrics:
            md.append(f"| {k.replace('_', ' ')} | {metrics[k]} |")
    for k in ["pressed", "dead end", "left the app", "stuck", "not clickable", "current page", "active option", "unnamed buttons", "broken link"]:
        if k in t:
            md.append(f"| dead-end run: {k} | {t[k]} |")
    rs = sweep["results"]
    md.append(f"| routes with console errors | {sum(1 for r in rs if (r.get('console_errors') or 0) > 0)} of {len(rs)} |")
    md.append(f"| routes with uncaught errors | {sum(1 for r in rs if (r.get('page_errors') or 0) > 0)} of {len(rs)} |")
    md.append(f"| axe critical + serious (elements) | {sum((r.get('axe_critical') or 0) + (r.get('axe_serious') or 0) for r in rs if isinstance(r.get('axe_critical'), int))} |")

    if issues:
        sev = Counter(i["severity"] for i in issues)
        code = Counter(i["code"] for i in issues)
        md += ["", "## Issues", "", f"**{len(issues)} issues:** " + ", ".join(f"{k} {v}" for k, v in sorted(sev.items())) + ". By type: " + ", ".join(f"{k} {v}" for k, v in code.most_common()) + ".", "", "| ID | Code | Sev | Issue | Where |", "|---|---|---|---|---|"]
        for i in sorted(issues, key=lambda i: (i["severity"], i["id"])):
            md.append(f"| {i['id']} | {i['code']} | {i['severity']} | {i['title']} | {i['route']} |")
    (here / "inventory.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"audits/{app}/inventory.md: {len(routes)} routes, {len(walks)} flows, {len(comps)} components, {len(issues)} issues")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "files")
