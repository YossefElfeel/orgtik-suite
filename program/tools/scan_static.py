"""Baseline code metrics for every suite app, before any refactor.

    python tools/scan_static.py

Writes audits/baseline-metrics.csv and audits/baseline-metrics.md. These counts are the
starting point of each app's ratchet: during its wave a count may only go down, and the
lint rule for it switches from warn to error when it reaches zero.

Every metric is a regex heuristic over .ts/.tsx/.js/.jsx outside node_modules and .next.
They're good enough to rank and track, not exact.
"""

import csv
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(HERE, "..", "audits")

APPS = {
    "sos": "somion-sos-frontend-main",
    "tasks": "task-manager-front-main",
    "files": "file-manager-dashboard-main",
    "sales": "sales-dashboardv2-main",
    "hr": "somion-hr-dashboard-main",
    "marketing": "digital-marketing-frontend-main",
    "content": "content-dashboard-somion-main",
    "chats": "somion-hq",
}
SKIP = {"node_modules", ".next", ".git", "public", "dist", "build"}
EXT = (".ts", ".tsx", ".js", ".jsx")
COLOR_PROPS = r"(?:bg|text|border|from|via|to|fill|stroke|ring|outline|shadow|decoration|placeholder|caret|accent|divide)"
PALETTE = r"(?:slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose)"

METRICS = {
    # colour
    "raw_hex": re.compile(r"(?<![\w&])#[0-9a-fA-F]{3,8}\b"),
    "arbitrary_color_classes": re.compile(COLOR_PROPS + r"-\[#"),
    "default_palette_classes": re.compile(r"\b" + COLOR_PROPS + r"-" + PALETTE + r"-\d{2,3}\b"),
    # direction (physical instead of logical: blocks RTL)
    "physical_direction_classes": re.compile(
        r"(?<![\w-])-?(?:m[lr]|p[lr]|scroll-m[lr]|scroll-p[lr])-(?:\d|\[|auto|px)"
        r"|(?<![\w-])(?:left|right)-(?:\d|\[|full|auto|px|1/2)"
        r"|\btext-(?:left|right)\b|\brounded-(?:[lr]|[tb][lr])(?:-|\b)|\bborder-[lr](?:-|\b)"
        r"|\bspace-x-\d|\bfloat-(?:left|right)\b|\borigin-(?:left|right)\b"
    ),
    # styling mechanics
    "inline_style_objects": re.compile(r"style=\{\{"),
    # component and icon layers
    "primitive_imports": re.compile(r"from\s+[\"'](?:@radix-ui/[^\"']+|radix-ui|@base-ui/react[^\"']*|react-aria-components)[\"']"),
    "lucide_imports": re.compile(r"from\s+[\"']lucide-react[\"']"),
    "iconify_uses": re.compile(r"<Icon\s[^>]*icon=|@iconify/react"),
    "phosphor_imports": re.compile(r"from\s+[\"']@phosphor-icons/react(?:/[^\"']*)?[\"']"),
    # copy and i18n
    "t_calls": re.compile(r"(?<![\w.])t\(\s*[\"'`]"),
    "literal_jsx_text": re.compile(r">\s*[A-Za-z][A-Za-z ,.'’!?-]{3,}\s*<"),
    # security leftovers
    "token_in_url": re.compile(r"[?&]token=|[?&]accessToken=|[?&]refreshToken="),
    "hardcoded_passwords": re.compile(r"password\s*[:=]\s*[\"'][^\"'\s]{6,}[\"']", re.I),
}


def scan(app_dir):
    counts = {k: 0 for k in METRICS}
    files = lines = use_client = 0
    for dirpath, dirnames, filenames in os.walk(app_dir):
        dirnames[:] = [d for d in dirnames if d not in SKIP]
        for f in filenames:
            if not f.endswith(EXT) or f.endswith(".d.ts"):
                continue
            try:
                text = open(os.path.join(dirpath, f), encoding="utf-8", errors="replace").read()
            except OSError:
                continue
            files += 1
            lines += text.count("\n") + 1
            if re.match(r"\s*[\"']use client[\"']", text):
                use_client += 1
            for k, rx in METRICS.items():
                counts[k] += len(rx.findall(text))
    return {"files": files, "lines": lines, "use_client_files": use_client, **counts}


def main():
    rows = []
    for key, folder in APPS.items():
        rows.append({"app": key, **scan(os.path.join(ROOT, folder))})
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "baseline-metrics.csv"), "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)

    cols = [k for k in rows[0] if k != "app"]
    md = ["# Baseline code metrics", "",
          "Generated by `tools/scan_static.py` from the app baselines. Each count is a heuristic; its job is to rank the work and to only go down during each app's wave.",
          "", "| Metric | " + " | ".join(r["app"] for r in rows) + " | Total |", "|---|" + "---|" * (len(rows) + 1)]
    for c in cols:
        md.append(f"| {c} | " + " | ".join(str(r[c]) for r in rows) + f" | {sum(r[c] for r in rows)} |")
    open(os.path.join(OUT, "baseline-metrics.md"), "w", encoding="utf-8").write("\n".join(md) + "\n")

    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(md[4:]))


if __name__ == "__main__":
    main()
