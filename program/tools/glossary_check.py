"""Compares the glossary's chosen terms with what the app catalogs say today.

    python tools/term_usage.py      first, to refresh glossary/term-usage.csv
    python tools/glossary_check.py

For every glossary concept the catalogs name, and every language, it lists the bare labels
(the term on its own) that differ from the chosen term, with the app and message key of each.
That list is each app's terminology fix list for its wave. It also lists where the specs mention
each concept, from specs/spec-register.csv.

Writes glossary/glossary-check.md and glossary/glossary-check.csv.

Matching is lenient on purpose: plural and inflected forms of the chosen term count as the same
term (Rechnung / Rechnungen, piano / piani, العميل / العملاء), so what's left is a different word.
"""
import csv
import re
from collections import Counter, defaultdict
from pathlib import Path

PROGRAM = Path(__file__).resolve().parent.parent
GLOSSARY = PROGRAM / "glossary"
LANGS = ["de", "fr", "it", "ar"]
# term_usage.py concept keys whose glossary key differs.
ALIAS = {"package": "service_package"}


def read(path):
    with open(path, encoding="utf-8-sig", newline="") as fh:
        return list(csv.DictReader(fh))


AR_WEAK = set("اويىةأإآءؤئ")


def norm(s):
    # Typographic punctuation does not change a term's meaning.
    return s.strip().rstrip(":.").lower().replace("’", "'").replace("‘", "'").replace("‑", "-")


def skeleton(word):
    """An Arabic word's consonants, without the article: broken plurals keep them (فاتورة / فواتير)."""
    word = re.sub(r"^(ال|لل)", "", word)
    return "".join(c for c in word if c not in AR_WEAK)


def word_match(a, b, lang):
    if a == b:
        return True
    if lang == "ar":
        sa, sb = skeleton(a), skeleton(b)
        k = min(3, len(sa), len(sb))
        return k >= 2 and sa[:k] == sb[:k]
    return b.startswith(a[: max(3, len(a) - 3)]) or a.startswith(b[: max(3, len(b) - 3)])


def same_term(chosen, found, lang):
    a, b = norm(chosen).split(), norm(found).split()
    if len(a) == len(b):
        return all(word_match(x, y, lang) for x, y in zip(a, b))
    # A one-word short form of a compound term (كوبون for كوبون خصم, Ticket for Ticket d'assistance).
    if len(b) == 1 and len(a) > 1:
        return word_match(a[0], b[0], lang)
    return False


def main():
    glossary = {g["key"]: g for g in read(GLOSSARY / "glossary.csv")}
    usage = read(GLOSSARY / "term-usage.csv")
    spec = read(PROGRAM / "specs" / "spec-register.csv")

    found = defaultdict(list)  # (key, lang) -> [(term, app, msg key)]
    for u in usage:
        if not u["bare"]:
            continue
        key = ALIAS.get(u["concept"], u["concept"])
        if key not in glossary:
            continue
        for lang in LANGS:
            if u[lang].strip():
                found[(key, lang)].append((u[lang].strip().rstrip(":."), u["app"], u["key"]))

    rows = []
    for (key, lang), items in sorted(found.items()):
        chosen = glossary[key][lang]
        for term, app, msg in items:
            if not same_term(chosen, term, lang):
                rows.append({"concept": key, "lang": lang, "chosen": chosen, "found": term, "app": app, "key": msg})

    def mentions(g):
        rx = re.compile(rf"\b{re.escape(g['en'])}s?\b", re.I)
        ids = [s["id"] for s in spec if rx.search(s["title_en"]) or rx.search(s["summary_en"])]
        return ids

    with open(GLOSSARY / "glossary-check.csv", "w", newline="", encoding="utf-8-sig") as fh:
        w = csv.DictWriter(fh, fieldnames=["concept", "lang", "chosen", "found", "app", "key"])
        w.writeheader()
        w.writerows(rows)

    by_app = Counter(r["app"] for r in rows)
    grouped = defaultdict(list)
    for r in rows:
        grouped[(r["concept"], r["lang"], r["chosen"], r["found"])].append(r)

    md = [
        "# Glossary check: what the catalogs say vs the chosen terms",
        "",
        "Generated by `tools/glossary_check.py` from `glossary.csv` and `term-usage.csv`. Only bare labels (the term on its own) are compared. Plural and inflected forms of the chosen term count as a match, so every row below is a different word. Each row is a change to make in that app's wave, once the term is approved.",
        "",
        f"**{len(rows)} labels differ** from the chosen terms: " + ", ".join(f"{a} {n}" for a, n in by_app.most_common()) + ".",
        "",
        "| Concept | Language | Chosen | Catalogs say | Apps (count) |",
        "|---|---|---|---|---|",
    ]
    for (concept, lang, chosen, term), rs in sorted(grouped.items(), key=lambda x: (x[0][0], x[0][1], -len(x[1]))):
        apps = Counter(r["app"] for r in rs)
        md.append(f"| {concept} | {lang} | {chosen} | {term} | " + ", ".join(f"{a} ({n})" for a, n in apps.most_common()) + " |")
    md += [
        "",
        "## Where the specs mention each concept",
        "",
        "From `specs/spec-register.csv` (titles and summaries, English). Useful when a term change touches a spec'd screen.",
        "",
        "| Concept | English | Spec items |",
        "|---|---|---|",
    ]
    for key, g in glossary.items():
        ids = mentions(g)
        if ids:
            shown = ", ".join(ids[:8]) + (f" and {len(ids) - 8} more" if len(ids) > 8 else "")
            md.append(f"| {key} | {g['en']} | {shown} |")
    (GLOSSARY / "glossary-check.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"{len(rows)} differing labels -> glossary/glossary-check.md, glossary-check.csv")


if __name__ == "__main__":
    main()
