// Finds every route of the website by following its links, and writes audits/website/routes.json.
//
// A route is a path plus, for the detail views a page renders from its URL fragment, that fragment
// (/services#/family/branding). In-page anchors (#top, #plan-builder) aren't routes. Legacy
// links (/projects/x, /pricing, Home.dc.html) are opened and recorded where the site's
// normalizeLocation() sends them; those pairs are the redirects the Website Manager has to keep.
//
//   node discover.mjs
import fs from "node:fs";
import path from "node:path";
import {pathToFileURL} from "node:url";
import { chromium } from "playwright";
import { OUT, ROUTES_FILE, SITE, SITE_DIR, load, newContext, siteCommit } from "./lib/site.mjs";

const PAGES = ["/", "/services", "/software", "/work", "/about", "/insights", "/contact", "/roadmap", "/legal", "/sign-in", "/sign-up"];
// Hidden "more" cards still have public CMS addresses. Discover them even before a visitor
// expands the list, using the same published route catalog as the production head generator.
const {addresses}=await import(pathToFileURL(path.join(SITE_DIR,'src/content/heads.js')));
PAGES.push(...addresses().filter(route=>!PAGES.includes(route)));
// Views no <a href> points to (the site switches them with buttons or builds them in code), and one
// example of every legacy path normalizeLocation() rewrites (src/reference/navigation.js). The
// legacy ones land on existing routes; the pairs are recorded as aliases.
const SEEDS = [
  "/legal#/privacy", "/legal#/terms", "/legal#/imprint", "/legal#/sitemap",
  "/software#/plans/single/annual/hr",
  "/privacy", "/terms", "/imprint", "/sitemap",
  "/platform", "/pricing", "/pricing/plans", "/platform/hr",
  "/projects", "/projects/orgtik-identity-system", "/insights/connected-digital-system",
  "/services/design", "/services/design/graphic-design", "/Home.dc.html",
];
const MISSING = "/audit-missing-page"; // the not-found view: no route serves it
const LIMIT = 300;

// A path plus its detail-view fragment. "#/" is the page's own overview, so it's the same route.
// The builders keep their state in the query (since c8be7fe: ?services=…&duration=…&terms=…). That
// is state, not a route: without dropping it every selection is a "new page" and the crawl never ends.
const STATE_KEYS = ["bundle", "duration", "engagement", "mode", "module", "modules", "plan", "plan-service", "renew", "services", "terms"];
const routeOf = (u) => {
  const q = new URLSearchParams(u.search);
  for (const k of STATE_KEYS) q.delete(k);
  const search = q.toString() ? `?${q}` : "";
  return (u.pathname.replace(/\/$/, "") || "/") + search + (u.hash.startsWith("#/") && u.hash !== "#/" ? u.hash : "");
};
const canonical = (href, base) => {
  const u = new URL(href, base);
  return u.origin === new URL(SITE).origin ? routeOf(u) : null;
};

const browser = await chromium.launch();
const routes = new Map(); // canonical route -> the route it was first linked from
const aliases = {}; // link as written -> where the site sent it
const queue = [...PAGES.map((p) => [p, "(start)"]), ...SEEDS.map((p) => [p, "(seed)"])];
const opened = new Set();
try {
  while (queue.length && routes.size < LIMIT) {
    const [candidate, from] = queue.shift();
    if (opened.has(candidate)) continue;
    opened.add(candidate);
    const context = await newContext(browser, 1440);
    const page = await context.newPage();
    try {
      await load(page, candidate);
      const landed = routeOf(new URL(page.url()));
      if (landed !== candidate) aliases[candidate] = landed;
      if (!routes.has(landed)) {
        routes.set(landed, from);
        console.log(`${landed}${landed !== candidate ? `   (from ${candidate})` : ""}`);
      }
      opened.add(landed);
      const hrefs = await page.evaluate(() => [...document.querySelectorAll("a[href]")].map((a) => a.getAttribute("href")));
      for (const href of hrefs) {
        if (!href || href === "#" || (href.startsWith("#") && !href.startsWith("#/"))) continue;
        if (/^(mailto|tel|javascript):/i.test(href)) continue;
        const next = href.startsWith("#/") ? canonical(landed.split("#")[0] + href, SITE) : canonical(href, page.url());
        if (next && !opened.has(next)) queue.push([next, landed]);
      }
    } catch (e) {
      console.log(`${candidate}: ${String(e.message).split("\n")[0]}`);
    } finally {
      await context.close();
    }
  }
} finally {
  await browser.close();
}

const list = [...routes.keys()].sort((a, b) => a.localeCompare(b));
if (!list.includes(MISSING)) list.push(MISSING);
fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(
  ROUTES_FILE,
  JSON.stringify({ site: SITE, commit: siteCommit(), at: new Date().toISOString(), note: "Generated by tools/qa/discover.mjs", routes: list, aliases }, null, 2) + "\n",
);
console.log(`\n${list.length} routes (${Object.keys(aliases).length} legacy links normalised) -> audits/website/routes.json`);
